const makeTemplateList = (template: string, items: string[]) =>
  items.map((item) => template.replace('{item}', item));

const uniqueList = (items: string[], targetCount: number, fallbackLabel: string) => {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of items) {
    const text = item.trim();
    if (!text || seen.has(text)) continue;
    seen.add(text);
    out.push(text);
    if (out.length >= targetCount) return out;
  }
  let i = 1;
  while (out.length < targetCount) {
    const text = `${fallbackLabel} category ${i}`;
    if (!seen.has(text)) {
      seen.add(text);
      out.push(text);
    }
    i += 1;
  }
  return out;
};

const toCategoryObjects = (items: string[], difficulty: StopTheFireDifficulty): StopTheFireCategory[] =>
  items.map((text) => ({ text, difficulty, tags: [] }));

